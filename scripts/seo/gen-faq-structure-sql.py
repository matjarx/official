"""SQL that gives three older blog posts' FAQ sections the structure FAQPage reads.

lib/blog-faq.ts builds FAQPage from a post's "Frequently asked questions" H2:
one H3 per question, then its answer. Three posts imported from WordPress
don't follow that, so their FAQs produce no schema:

  facebook-page-setup-guide, tiktok-growth-limit-switch-business-account
      each question and answer is one paragraph ("Question? Answer.")
      -> split at the first "? " into an H3 and a paragraph
  local-seo-for-small-business-guide
      the questions are H2s -> H3s

facebook-page-setup-guide also has its closing heading flattened into the
last paragraph ("Conclusion: Turbocharge Your Facebook Page Andha dhund ...");
it becomes an H2 again so the FAQ section ends where the reader sees it end.
No words are added, removed or changed.

  python3 -I scripts/seo/gen-faq-structure-sql.py /seo-data/supabase-export/marketing_blog_posts.json /seo-data/migrations

Writes blog-faq-structure.sql and its rollback. Each UPDATE matches the post
only while its body is exactly as exported; the script aborts (changing
nothing) otherwise. A second run changes nothing. Never connects to a database.
"""
import json
import os
import re
import sys

SRC, OUT = sys.argv[1], sys.argv[2]
posts = {r['slug']: r for r in json.load(open(SRC, encoding='utf-8'))}
FAQ = re.compile(r'^(frequently asked questions|faqs?)\b', re.I)
FB_CONCLUSION = 'Conclusion: Turbocharge Your Facebook Page '


def faq_start(body):
    return next(i for i, b in enumerate(body) if b['t'] == 'h' and FAQ.match(b['text'].strip()))


def split_inline(body):
    i = faq_start(body)
    out = body[:i + 1]
    for b in body[i + 1:]:
        if b['t'] == 'h':
            out.append(b)
            out.extend(body[body.index(b) + 1:])
            return out
        if b['t'] == 'p' and b['text'].startswith(FB_CONCLUSION):
            out.append({'t': 'h', 'text': FB_CONCLUSION.strip()})
            out.append({'t': 'p', 'text': b['text'][len(FB_CONCLUSION):]})
            out.extend(body[body.index(b) + 1:])
            return out
        q, sep, a = b['text'].partition('? ')
        assert b['t'] == 'p' and sep, b
        out.append({'t': 'h3', 'text': q + '?'})
        out.append({'t': 'p', 'text': a})
    return out


def h2_to_h3(body):
    i = faq_start(body)
    return body[:i + 1] + [{**b, 't': 'h3'} if b['t'] == 'h' else b for b in body[i + 1:]]


CHANGES = {
    'facebook-page-setup-guide': split_inline,
    'tiktok-growth-limit-switch-business-account': split_inline,
    'local-seo-for-small-business-guide': h2_to_h3,
}


def words(body):
    return ' '.join(' '.join([b.get('text', '')] + b.get('items', [])) for b in body).split()


def lit(v):
    return "'" + json.dumps(v, ensure_ascii=False).replace("'", "''") + "'"


def sq(v):
    return "'" + v.replace("'", "''") + "'"


fwd, back = [], []
for slug, fn in CHANGES.items():
    old = posts[slug]['body']
    new = fn(old)
    assert words(new) == words(old), slug  # structure only, same words
    questions = [b['text'] for b in new[faq_start(new) + 1:] if b['t'] == 'h3']
    print(f'{slug}: {len(questions)} questions')
    for q in questions:
        print('   ', q)
    for out, frm, to in ((fwd, old, new), (back, new, old)):
        out.append(f"""  -- {slug}
  EXECUTE 'SELECT body::text::jsonb FROM marketing_blog_posts WHERE slug = $1' INTO b USING {sq(slug)};
  IF b IS NULL THEN
    RAISE NOTICE '{slug} not found; skipped.';
  ELSIF b = {lit(to)}::jsonb THEN
    RAISE NOTICE '{slug} already done; skipped.';
  ELSIF b = {lit(frm)}::jsonb THEN
    EXECUTE format('UPDATE marketing_blog_posts SET body = $1::%s, updated_at = now() WHERE slug = $2', body_type)
      USING {lit(to)}, {sq(slug)};
  ELSE
    RAISE EXCEPTION '{slug} body changed since the export; nothing applied.';
  END IF;
""")


def wrap(head, parts):
    return (head + "\n\nBEGIN;\nDO $mx$\nDECLARE\n  b jsonb;\n  body_type text;\nBEGIN\n"
            "  SELECT CASE udt_name WHEN 'jsonb' THEN 'jsonb' WHEN 'json' THEN 'json' ELSE 'text' END INTO body_type\n"
            "    FROM information_schema.columns WHERE table_name = 'marketing_blog_posts' AND column_name = 'body'\n"
            "   ORDER BY table_schema = 'public' DESC LIMIT 1;\n\n" + '\n'.join(parts) + "END\n$mx$;\nCOMMIT;\n")


os.makedirs(OUT, exist_ok=True)
open(os.path.join(OUT, 'blog-faq-structure.sql'), 'w', encoding='utf-8').write(wrap(
    '-- GENERATED by scripts/seo/gen-faq-structure-sql.py -- review before running.\n'
    '-- Gives the FAQ sections of three older posts one H3 per question, so their\n'
    '-- FAQPage schema is generated. No words change. All or nothing; safe to re-run.', fwd))
open(os.path.join(OUT, 'blog-faq-structure-rollback.sql'), 'w', encoding='utf-8').write(wrap(
    '-- Puts the three FAQ sections back as they were in the export.', back))
