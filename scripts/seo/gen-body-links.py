#!/usr/bin/env python3
"""Generate src/lib/generated/body-links.json from the SEO sheet.

Source: tab "Internal links", column "Add these links (target -> anchor
text)", exported to /seo-data/internal-links.csv. Spec group 5, item 4:
add these links into the body of the money pages, with the anchor text
given, and only to URLs that return 200 today; list the skipped ones.

    python3 scripts/seo/gen-body-links.py [internal-links.csv] [--status FILE]

Every source and target URL is fetched from https://matjarx.com (no
redirects followed) unless --status names a file of "<code> <path>"
lines from an earlier check. A link is kept only when both ends are 200.
"""
import csv, json, re, sys, urllib.request, urllib.error
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / 'src/lib/generated/body-links.json'

status_file = sys.argv[sys.argv.index('--status') + 1] if '--status' in sys.argv else None
args = [a for a in sys.argv[1:] if not a.startswith('--') and a != status_file]
CSV = Path(args[0] if args else '/seo-data/internal-links.csv')

# The money pages named in spec group 5, item 4.
MONEY = {'/', '/done-for-you-website', '/pricing', '/local-national-and-global-seo', '/growth-marketing-service',
         '/concierge-service', '/complete-website-audit-for-organic-visibility', '/best-website-builder-pakistan',
         '/templates', '/website-examples'}
MONEY_PREFIX = ('/website-design-', '/website-for-', '/templates/', '/alternatives/matjarx-vs-')

LINE = re.compile(r'^\s*(/\S*)\s+→\s+“(.+?)”\s*$')


class NoRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, *a, **k):
        return None


opener = urllib.request.build_opener(NoRedirect)


def live_status(path, cache={}):
    if path not in cache:
        try:
            cache[path] = opener.open(urllib.request.Request('https://matjarx.com' + path, method='GET'), timeout=40).status
        except urllib.error.HTTPError as e:
            cache[path] = e.code
        except Exception:
            cache[path] = 0
    return cache[path]


known = {}
if status_file:
    for line in open(status_file):
        code, path = line.split()
        known[path] = int(code)


# Pages this branch adds: 200 once it ships, so links to them are kept.
SHIPPED_HERE = {'/locations'}


def status(path):
    if path in SHIPPED_HERE:
        return 200
    return known[path] if path in known else live_status(path)


links, skipped = {}, []
for row in csv.DictReader(open(CSV, encoding='utf-8-sig')):
    src = row['URL'].strip()
    if not (src in MONEY or src.startswith(MONEY_PREFIX)):
        continue
    pairs = [m.groups() for m in map(LINE.match, row['Add these links (target → anchor text)'].split('\n')) if m]
    if not pairs:
        continue
    src_status = status(src)
    for href, anchor in pairs:
        code = status(href)
        if src_status != 200 or code != 200 or href == src:
            skipped.append({'page': src, 'href': href, 'anchor': anchor,
                            'why': f'page returns {src_status}' if src_status != 200 else f'target returns {code}'})
            continue
        links.setdefault(src, [])
        if [href, anchor] not in links[src]:
            links[src].append([href, anchor])

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(json.dumps({
    '_comment': 'GENERATED by scripts/seo/gen-body-links.py from the SEO sheet, tab "Internal links". Do not edit by hand.',
    'links': links,
    'skipped': skipped,
}, ensure_ascii=False, indent=1) + '\n')
print(f'{sum(map(len, links.values()))} links on {len(links)} pages; {len(skipped)} skipped -> {OUT.relative_to(ROOT)}')
