#!/usr/bin/env python3
"""Write /seo-data/migrations/group6-content.sql and its rollback.

Group 6, items 1 and 2, for the copy that lives in marketing_content rather
than in code. Each change is a guarded text replacement inside one row, so
it is idempotent and touches nothing else. Run it AFTER plan-copy.sql: that
file refuses to run on rows changed since the export, and this one changes
`about`, `videos`, `services/dfy` and `_site_settings`.
"""
from pathlib import Path

SECURITY = 'SSL on every site, plus security and platform updates.'
CLAIM = 'Our team has 7+ years of experience and has built 70,000+ websites, first under our US brand and now in Pakistan.'

CHANGES = [
    ('about', '"70,000+ websites across 1,000+ business categories — everything',
              f'"{CLAIM} They span 1,000+ business categories — everything'),
    ('about', ' But we serve 70,000+ businesses across wildly different industries — chances are we\'re a great fit.',
              f' {CLAIM} Chances are we\'re a great fit.'),
    ('videos', 'this video explains MatjarX in context — how we\'ve helped 70,000+ Pakistani businesses get online.',
               f'this video explains MatjarX in context. {CLAIM}'),
    ('services/dfy', 'More than 70,000 businesses trust MatjarX. Your business deserves to join them.', CLAIM),
    ('_site_settings', 'MatjarX builds complete small business websites in 7 days for Rs. 22,500 — done-for-you design, SEO and growth marketing for businesses across Pakistan and the Gulf.',
                       'MatjarX builds complete small business websites in 7 days, from Rs. 4,500/month + Rs. 22,500 setup — done-for-you design, SEO and growth marketing.'),
    # Decisions of 18 Oct.
    ('about', '{"label": "websites built", "value": "70,000+"}', '{"label": "websites built by our team", "value": "70,000+"}'),
    ('services/dfy', '{"label": "websites built", "value": "70,000"}', '{"label": "websites built by our team", "value": "70,000+"}'),
    ('about', 'Zero security breaches in 8+ years serving 70,000+ customers. All data', f'{SECURITY} All data'),
    ('services/dfy', '"Zero security breaches in 8+ years serving 70,000+ customers"', f'"{SECURITY}"'),
    ('services/dfy', '100% secure. In 8+ years serving 70,000+ customers: zero security breaches, zero cyber attacks, data stored on secured AWS servers, SSL certificate on every website, automatic updates and patches, daily backups.',
                     f'{SECURITY} Your data is stored on secured AWS servers, with daily backups.'),
    ('services/dfy', 'Completely zero-risk. Unmatched customer service.', "No long-term contract. Cancel with 30 days' notice. Unmatched customer service."),
    # 18 Oct, later: years match the claim; team size and client countries
    # as confirmed by MatjarX (clients' countries, not offices).
    ('about', "8+ years helping small businesses get online. We've grown from a small team to 120 professionals across 4 countries, but",
              "7+ years helping small businesses get online. We're a team of 18–20 people, serving clients across Pakistan, the UAE, the UK and the US, but"),
]

for _, old, new in CHANGES:
    assert '\\' not in old + new, 'a value that JSON escapes would not match data::text'

sq = lambda s: "'" + s.replace("'", "''") + "'"


def write(path, pairs, title, extra=()):
    extra = list(extra)
    out = [f'-- {title}', '-- Generated by scripts/seo/gen-group6-sql.py. Each statement changes one string in',
           '-- one row, and only while the old string is there, so a second run does nothing.', '', 'BEGIN;', '']
    for slug, old, new in pairs:
        out += [f'UPDATE marketing_content SET data = replace(data::text, {sq(old)}, {sq(new)})::jsonb, updated_at = now()',
                f' WHERE slug = {sq(slug)} AND strpos(data::text, {sq(old)}) > 0;', '']
    out += extra
    out += ['COMMIT;', '']
    Path(path).write_text('\n'.join(out), encoding='utf-8')


import json
OLD_BAR = {"text": "49% off on Platinum Plan", "enabled": False, "bg_color": "#a0b082", "end_date": "2026-09-25", "link_url": "/pricing",
           "link_text": "Claim Offer Now", "start_date": "2026-09-24", "text_color": "#ff0000", "dismissible": False}
NEW_BAR = {"enabled": True, "text": "Free website SEO check:", "link_text": "get your report",
           "link_url": "/complete-website-audit-for-organic-visibility",
           "bg_color": "linear-gradient(90deg, #003366 0%, #2E6EA8 20%, #696D34 42%, #C9A227 60%, #C4262E 80%, #7A2E6B 100%)",
           "text_color": "#FFFFFF", "dismissible": False}
def bar(frm, to, note):
    return [f'-- {note}',
            f"UPDATE marketing_content SET data = {sq(json.dumps(to, ensure_ascii=False))}::jsonb, updated_at = now()",
            f" WHERE slug = '_announcement_bar' AND data = {sq(json.dumps(frm, ensure_ascii=False))}::jsonb;", '']

write('/seo-data/migrations/group6-content.sql', CHANGES,
      'Group 6: the 70,000 claim (prose and stat tiles), the default meta description, the security lines, the contract line and the announcement bar. Run after plan-copy.sql.',
      bar(OLD_BAR, NEW_BAR, 'Announcement bar: replaced whole, and only while it still holds the expired, disabled "49% off on Platinum Plan" campaign from the export.'))
write('/seo-data/migrations/group6-content-rollback.sql', [(s, n, o) for s, o, n in CHANGES],
      'Rollback of group6-content.sql: puts the old strings back.',
      bar(NEW_BAR, OLD_BAR, 'Announcement bar: back to the old campaign row, only while it is still the new one.'))
print('wrote group6-content.sql and group6-content-rollback.sql')
